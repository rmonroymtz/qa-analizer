import { spawn } from 'node:child_process';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { join, resolve } from 'node:path';
import type { CriterionResult } from '../../domain/criterion-result.js';
import type { GeneratedSuite } from '../../ports/test-generator.js';
import type { RunContext, TestRunner } from '../../ports/test-runner.js';
import type { GuardOptions } from './read-only-guard.js';
import { classifyResults, type PlaywrightJsonReport } from './result-classifier.js';

export interface LaunchResult {
  exitCode: number | null;
  stderrTail: string;
}

/** Runs `node <args>`; injectable so unit tests never start a browser. */
export type ProcessLauncher = (
  args: string[],
  options: { cwd: string; env: NodeJS.ProcessEnv; timeoutMs: number },
) => Promise<LaunchResult>;

export interface PlaywrightTestRunnerOptions {
  launch?: ProcessLauncher;
  /** Absolute path to the `@playwright/test` CLI entry. */
  cliPath?: string;
  /** Absolute `file:` URL of `@playwright/test`, imported by the generated files. */
  playwrightModuleUrl?: string;
  /** Absolute `file:` URL of the compiled read-only guard module. */
  guardModuleUrl?: string;
  timeoutMs?: number;
}

export const SPEC_FILE = 'verification.spec.ts';
export const TEST_TIMEOUT_MS = 60_000;
const DEFAULT_RUN_TIMEOUT_MS = 20 * 60_000;
const STDERR_TAIL_CHARS = 2_000;
/** Env vars that must never reach AI-generated code. */
const SECRET_ENV = /TOKEN|SECRET|PASSWORD|PASSWD|API_KEY|PRIVATE|CREDENTIAL|^JIRA_|^ANTHROPIC_|^TEST_USER$/i;
/** Node-side HTTP clients bypass the browser route guard. */
const DIRECT_HTTP = [/\brequest\s*\.\s*(?:post|put|patch|delete|fetch)\s*\(/, /(?<![.\w])fetch\s*\(/];
/** Settings the read-only guard relies on; a spec must not override them. */
const GUARD_OVERRIDES = [/\bserviceWorkers\b/, /\brouteWebSocket\b/, /\bunroute(?:All)?\b/];

export function sanitizedChildEnv(env: NodeJS.ProcessEnv): NodeJS.ProcessEnv {
  return Object.fromEntries(Object.entries(env).filter(([name]) => !SECRET_ENV.test(name)));
}

export interface FixturesTemplateInput {
  playwrightModuleUrl: string;
  guardModuleUrl: string;
  /** Set only in read-only mode. */
  guard: GuardOptions | undefined;
}

/** The `qa-fixtures.ts` module that generated specs import `test` and `expect` from. */
export function renderFixtures(input: FixturesTemplateInput): string {
  const lines = ['// Generated by qa-analyzer. Do not edit.', `import { test as base, expect } from '${input.playwrightModuleUrl}';`];
  if (input.guard === undefined) {
    lines.push('', 'export const test = base;');
  } else {
    lines.push(
      `import { installReadOnlyGuard } from '${input.guardModuleUrl}';`,
      '',
      `const GUARD_OPTIONS = ${JSON.stringify(input.guard)};`,
      '',
      '// Read-only mode: every browser request goes through the guard before the test starts.',
      'export const test = base.extend({',
      '  context: async ({ context }, use) => {',
      '    await installReadOnlyGuard(context, GUARD_OPTIONS);',
      '    await use(context);',
      '  },',
      '  request: async ({}, use) => {',
      "    throw new Error('ERR_BLOCKED_BY_CLIENT: the API request fixture is disabled in read-only mode');",
      '  },',
      '});',
    );
  }
  lines.push('', 'export { expect };', '');
  return lines.join('\n');
}

export interface ConfigTemplateInput {
  playwrightModuleUrl: string;
  testDir: string;
  outputDir: string;
  baseUrl: string;
  storageStatePath?: string | undefined;
  /** Read-only mode: block service workers, which could bypass the route guard. */
  readOnly?: boolean;
}

/** The Playwright config, with absolute paths so it works from any working directory. */
export function renderConfig(input: ConfigTemplateInput): string {
  const config = {
    testDir: input.testDir,
    testMatch: '**/*.spec.ts',
    timeout: TEST_TIMEOUT_MS,
    retries: 1,
    workers: 1,
    fullyParallel: false,
    outputDir: join(input.outputDir, 'test-results'),
    reporter: [['json', { outputFile: join(input.outputDir, 'results.json') }], ['list']],
    use: {
      baseURL: input.baseUrl,
      ...(input.storageStatePath ? { storageState: input.storageStatePath } : {}),
      ...(input.readOnly ? { serviceWorkers: 'block' } : {}),
      browserName: 'chromium',
      headless: true,
      trace: 'retain-on-failure',
      screenshot: 'only-on-failure',
    },
  };
  return [
    '// Generated by qa-analyzer. Do not edit.',
    `import { defineConfig } from '${input.playwrightModuleUrl}';`,
    '',
    `export default defineConfig(${JSON.stringify(config)});`,
    '',
  ].join('\n');
}

const defaultLauncher: ProcessLauncher = (args, options) =>
  new Promise((resolvePromise) => {
    let stderr = '';
    const child = spawn(process.execPath, args, { cwd: options.cwd, env: options.env, stdio: ['ignore', 'inherit', 'pipe'] });
    const timer = setTimeout(() => child.kill('SIGKILL'), options.timeoutMs);
    child.stderr?.on('data', (chunk: Buffer) => {
      process.stderr.write(chunk);
      stderr = (stderr + chunk.toString('utf8')).slice(-STDERR_TAIL_CHARS);
    });
    child.on('error', (error) => {
      clearTimeout(timer);
      resolvePromise({ exitCode: null, stderrTail: `${stderr}\n${error.message}`.trim() });
    });
    child.on('close', (code, signal) => {
      clearTimeout(timer);
      resolvePromise({ exitCode: code, stderrTail: signal ? `${stderr}\nkilled by ${signal}`.trim() : stderr.trim() });
    });
  });

function inconclusiveAll(suite: GeneratedSuite, ctx: RunContext, reason: string): CriterionResult[] {
  return classifyResults({ suites: [], errors: [{ message: reason }] }, suite, ctx.ticket);
}

/** Writes the generated spec next to its fixtures and config, runs it, and classifies the results. */
export class PlaywrightTestRunner implements TestRunner {
  constructor(private readonly options: PlaywrightTestRunnerOptions = {}) {}

  async run(suite: GeneratedSuite, ctx: RunContext): Promise<CriterionResult[]> {
    if (ctx.policy.mode === 'read-only' && DIRECT_HTTP.some((pattern) => pattern.test(suite.specCode))) {
      return inconclusiveAll(suite, ctx, 'generated spec uses a direct HTTP client, which is not allowed in read-only mode');
    }
    if (ctx.policy.mode === 'read-only' && GUARD_OVERRIDES.some((pattern) => pattern.test(suite.specCode))) {
      return inconclusiveAll(suite, ctx, 'generated spec overrides a read-only guard setting, which is not allowed in read-only mode');
    }
    const outputDir = resolve(ctx.outputDir);
    const generatedDir = join(outputDir, 'generated');
    const resultsPath = join(outputDir, 'results.json');
    const configPath = join(generatedDir, 'playwright.config.mjs');
    const requireFromHere = createRequire(import.meta.url);
    const playwrightModuleUrl = this.options.playwrightModuleUrl ?? import.meta.resolve('@playwright/test');
    const guardModuleUrl = this.options.guardModuleUrl ?? new URL('./read-only-guard.js', import.meta.url).href;
    const cliPath = this.options.cliPath ?? requireFromHere.resolve('@playwright/test/cli');

    await mkdir(generatedDir, { recursive: true });
    await rm(resultsPath, { force: true });
    const guard: GuardOptions | undefined =
      ctx.policy.mode === 'read-only'
        ? { baseUrl: ctx.baseUrl, allowedMutations: ctx.policy.allowedMutations, allowedHosts: ctx.policy.allowedHosts ?? [] }
        : undefined;
    // The package.json pins ESM so absolute `file:` imports work whatever the surrounding repo uses.
    await writeFile(join(generatedDir, 'package.json'), `${JSON.stringify({ type: 'module' })}\n`);
    await writeFile(join(generatedDir, 'qa-fixtures.ts'), renderFixtures({ playwrightModuleUrl, guardModuleUrl, guard }));
    await writeFile(join(generatedDir, SPEC_FILE), suite.specCode);
    await writeFile(
      configPath,
      renderConfig({
        playwrightModuleUrl,
        testDir: generatedDir,
        outputDir,
        baseUrl: ctx.baseUrl,
        storageStatePath: ctx.storageStatePath,
        readOnly: guard !== undefined,
      }),
    );

    const launch = this.options.launch ?? defaultLauncher;
    // A non-zero exit only means some test failed; results.json is the source of truth.
    const { exitCode, stderrTail } = await launch([cliPath, 'test', '--config', configPath], {
      cwd: generatedDir,
      env: sanitizedChildEnv(process.env),
      timeoutMs: this.options.timeoutMs ?? DEFAULT_RUN_TIMEOUT_MS,
    });

    let report: PlaywrightJsonReport;
    try {
      report = JSON.parse(await readFile(resultsPath, 'utf8')) as PlaywrightJsonReport;
      if (!Array.isArray(report.suites)) throw new Error('missing suites');
    } catch {
      const tail = stderrTail.slice(-240).replace(/\s+/g, ' ').trim();
      return inconclusiveAll(suite, ctx, `test execution failed (exit code ${String(exitCode)}): ${tail || 'no output'}`);
    }
    return classifyResults(report, suite, ctx.ticket);
  }
}
